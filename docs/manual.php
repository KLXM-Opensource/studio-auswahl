<?php /** Handbuch · Kapitel „Bildauswahl“ (Erweiterung auswahl) */ ?>
  <p class="lead">Mit der <b>Bildauswahl</b> zeigen Sie ein Shooting Ihrer Kundin oder Ihrem Kunden über einen geheimen Link. Dort werden Fotos und Videos angesehen, mit einem Herz ausgewählt, auf Wunsch mit Notizen versehen und die Auswahl verbindlich abgeschickt – ohne Konto und ohne App.</p>
  <h3>Ein Shooting anlegen</h3>
  <ol>
    <li>In der <b>Mediathek</b> eine neue Sammlung anlegen (z. B. „Hochzeit Anna &amp; Ben“) und die Bilder und Videos hineinladen. Reihenfolge und Dateinamen übernimmt die Auswahl.</li>
    <li>Menü <b>Bildauswahl → Neues Shooting</b>: Titel, Sammlung, Datum, eine kurze Begrüßung, Name und E-Mail-Adresse.</li>
    <li>Regeln: <b>Dateien im Paket</b> (z. B. 20 – mehr lassen sich nicht auswählen; 0 = beliebig viele), <b>Auswahl bis</b> (Frist), <b>PIN</b> (4–12 Ziffern oder Buchstaben, getrennt vom Link weitergeben, z. B. per SMS), Notizen erlauben, Herunterladen der Originale erlauben.</li>
  </ol>
  <h3>Link teilen</h3>
  <ul>
    <li>Auf der Seite des Shootings: <b>Kopieren</b> oder <b>Einladung senden</b> (E-Mail mit Link, Paketgröße und Frist – die PIN steht nie in der E-Mail).</li>
    <li><b>Neuen Link erzeugen</b> macht den alten ungültig – etwa, wenn er an die falsche Adresse ging. Eine neue PIN sperrt bereits geöffnete Sitzungen.</li>
  </ul>
  <h3>Was Ihre Kundin bzw. Ihr Kunde sieht</h3>
  <ul>
    <li>Die Bilder im Design Ihrer Website, in ihren Originalformaten, mit Nummer und Dateiname. Oben steht, wie viele schon ausgewählt sind („3 / 20“).</li>
    <li>Herz antippen = auswählen. Ein Klick aufs Bild öffnet die Großansicht: mit Pfeiltasten oder Wischen weiter, <kbd>P</kbd> wählt aus, dazu eine Notiz je Bild („bitte etwas heller“) und – wenn erlaubt – <b>Herunterladen</b>.</li>
    <li>Filter „Ausgewählt“ und „Mit Notiz“ helfen beim Überprüfen. Alles wird sofort gespeichert; die Seite kann jederzeit geschlossen und später wieder geöffnet werden.</li>
    <li><b>Auswahl abschicken</b> (mit optionaler Nachricht) macht die Auswahl verbindlich. Sie bekommen eine E-Mail mit allen Dateinamen und Notizen, auf Wunsch auch eine Push-Mitteilung.</li>
  </ul>
  <h3>Auswahl übernehmen</h3>
  <ul>
    <li>Auf der Seite des Shootings stehen die ausgewählten Bilder mit Notizen und darüber die <b>Dateinamen</b>, durch Komma getrennt – kopieren und in Lightroom, Capture One oder Photo Mechanic in den Filter einfügen.</li>
    <li><b>CSV herunterladen</b>: alle Dateien mit Nummer, Name, ausgewählt ja/nein und Notiz.</li>
    <li><b>Wieder öffnen</b> erlaubt Änderungen und erneutes Abschicken, <b>Abschließen</b> beendet das Shooting (der Link zeigt dann nur noch einen Hinweis). Die Dateien bleiben in der Mediathek.</li>
  </ul>
  <h3>Gut zu wissen</h3>
  <ul>
    <li>Die Bilder haben zufällige Adressen, die niemand erraten kann. Wer die Adresse eines einzelnen Bildes weitergibt, gibt dieses Bild weiter – für vertrauliche Shootings zusätzlich eine PIN setzen.</li>
    <li>Die Seiten der Auswahl erscheinen nie in der Suche, in der Sitemap oder bei Suchmaschinen.</li>
    <li>Hinweise an das Studio gehen an die Empfänger der Website oder an die Adressen unter <b>Bildauswahl → Einstellungen</b>.</li>
  </ul>
